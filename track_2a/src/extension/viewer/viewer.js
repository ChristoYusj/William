import { pdfjsLib, fetchDoc, extract, summarize, summaryHtml, bindTopics, shared, downloadBlob, esc, buildText } from "../shared/engine.js";
import { recordHtml } from "../shared/render.js";

const file = new URLSearchParams(location.search).get("file");
const $ = (id) => document.getElementById(id);
const out = $("out"), status = $("status");
let docPromise; // fetchDoc result (pages text + OPD hints)

$("orig").href = file;
$("docname").textContent = decodeURIComponent((file || "").split("/").pop().split("?")[0]).slice(0, 80);
document.title = "William — " + $("docname").textContent;

function busy(msg) { status.textContent = msg; out.innerHTML = '<div class="spin"></div>'; }
function fail(e) { status.textContent = ""; out.innerHTML = `<p class="err">${esc(e.message || e)}</p>`; }

async function render() {
  const r = await fetch(file, { credentials: "include" });
  const data = new Uint8Array(await r.arrayBuffer());
  const pdf = await pdfjsLib.getDocument({ data: data.slice() }).promise;
  const host = $("pages");
  const width = Math.min(host.clientWidth - 40, 900);
  for (let i = 1; i <= pdf.numPages; i++) {
    const page = await pdf.getPage(i);
    const base = page.getViewport({ scale: 1 });
    const vp = page.getViewport({ scale: width / base.width });
    const wrap = document.createElement("div");
    wrap.className = "page";
    wrap.id = "page-" + i;
    wrap.style.width = vp.width + "px";
    wrap.style.height = vp.height + "px";
    wrap.style.setProperty("--scale-factor", vp.scale);
    const canvas = document.createElement("canvas");
    const dpr = window.devicePixelRatio || 1;
    canvas.width = vp.width * dpr; canvas.height = vp.height * dpr;
    canvas.style.width = vp.width + "px"; canvas.style.height = vp.height + "px";
    const tl = document.createElement("div");
    tl.className = "textLayer";
    wrap.append(canvas, tl);
    host.appendChild(wrap);
    await page.render({ canvasContext: canvas.getContext("2d"), viewport: vp, transform: dpr !== 1 ? [dpr, 0, 0, dpr, 0, 0] : null }).promise;
    await new pdfjsLib.TextLayer({ textContentSource: page.streamTextContent(), container: tl, viewport: vp }).render();
  }
}

function goPage(n) {
  const el = $("page-" + n);
  if (!el) return;
  el.scrollIntoView({ behavior: "smooth", block: "start" });
  el.classList.add("flash");
  setTimeout(() => el.classList.remove("flash"), 1500);
}

document.addEventListener("selectionchange", () => {
  $("bSel").disabled = !(window.getSelection()?.toString().trim().length > 20);
});

async function doSummary(text, label) {
  busy(`Apertus is summarising the ${label}…`);
  try {
    const res = await summarize(text);
    status.textContent = `Summary of the ${label} · language ${res.language}${res.truncated ? " · long document: beginning only" : ""}`;
    out.innerHTML = summaryHtml(res) + '<div class="small muted">Highlighted topics → Swiss news (Google News, CH edition). Generated by Apertus; check against the document.</div>';
    bindTopics(out, res);
  } catch (e) { fail(e); }
}

$("bSum").onclick = async () => {
  const { prompts } = await shared();
  const doc = await docPromise;
  doSummary(buildText(doc.pages, prompts.max_doc_chars)[0], "document");
};
$("bSel").onclick = () => doSummary(window.getSelection().toString(), "selection");
$("bExt").onclick = async () => {
  busy("Apertus is extracting the affair (this can take ~30–60 s)…");
  try {
    const doc = await docPromise;
    const rec = await extract(doc);
    const { vocab } = await shared();
    status.textContent = "OpenParlData common structure (opd-affair/0.1) — click p.N to jump to the evidence";
    out.innerHTML = recordHtml(rec, vocab) +
      '<p><button class="btn" id="dl">Download JSON</button></p><pre class="json"></pre>';
    out.querySelector("pre").textContent = JSON.stringify(rec, null, 1);
    out.querySelectorAll(".pg").forEach((a) => (a.onclick = () => goPage(+a.dataset.page)));
    out.querySelector("#dl").onclick = () => downloadBlob(new Blob([JSON.stringify(rec, null, 2)], { type: "application/json" }),
      ($("docname").textContent.replace(/\.pdf$/i, "") || "affair") + ".opd-affair.json");
  } catch (e) { fail(e); }
};

if (!file) fail(new Error("No file given."));
else {
  docPromise = fetchDoc(file);
  docPromise.catch(fail);
  render().catch(fail);
}
